/**
 * Ключ записи по тексту: строчные, без знаков препинания и лишних пробелов.
 * «Кот спит.» и «кот спит» — одна запись. Буква «ё» сохраняется: «все» и
 * «всё» звучат по-разному.
 */
export const audioKey = (text: string): string =>
  text
    .toLocaleLowerCase("ru")
    .replace(/[.,!?«»"“”:;()—–-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
