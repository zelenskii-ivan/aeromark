import type { Lesson } from "../lesson.ts";
import { lesson, maker } from "../lesson-kit.ts";

/**
 * Русский язык, 1 класс: главные темы года по УМК «Перспектива»
 * (Климанова, Бабушкина) — ударение, предложение, большая буква,
 * сочетания жи-ши, ча-ща, чу-щу и парные звонкие и глухие согласные.
 *
 * Как и «Лук и люк», правило не объявляется, а выводится: ребёнок сначала
 * сталкивается с задачей, сравнивает пары слов, и только потом видит
 * формулировку. Звуки называются звуками ([ж]), а не буквами («жэ»).
 */

const CHARACTER = "Штурман Вера";

export function stressLesson(): Lesson {
  const s = maker("rs", CHARACTER);
  return lesson(
    "ru-stress",
    "Ударный слог",
    "Находить ударный слог в слове, позвав слово голосом",
    "Деление слова на слоги",
    [
      s.say("hook", "hook", "Послушай: замок на двери и замок у принцессы. Буквы одни и те же, а слова разные. Всё решает один сильный слог."),
      s.choice("warm", "warmup", "Слоги", "Сколько слогов в слове «ракета»?", ["2", "3", "4"], "3", "Хлопай на каждый слог: ра-ке-та."),
      s.choice("trial", "trial", "Слоги", "Какой слог в слове «ракета» звучит сильнее остальных?", ["ра", "ке", "та"], "ке", "Пока это трудно — так и должно быть. Сейчас разберёмся вместе."),
      s.say("explore-say", "explore", "Позови слово, будто зовёшь друга издалека: ра-кеее-та. Слог, который сам тянется и звучит сильнее, называется ударным. В слове он только один."),
      s.choice("explore", "explore", "Слоги", "Позови слово «пилот». Какой слог ударный?", ["пи", "лот"], "лот", "Пи-лооот. Какой слог тянется?"),
      s.match("model", "model", "Слоги", "Соедини слово и его ударный слог.", [["пилот", "лот"], ["небо", "не"], ["крыло", "ло"]], "Позови каждое слово и послушай, какой слог тянется."),
      s.choice("sign", "sign", "Слоги", "Как в схеме слова показывают ударный слог?", ["Знаком ударения над гласной", "Точкой в конце", "Большой буквой"], "Знаком ударения над гласной", "Ударение ставят над гласной буквой ударного слога."),
      s.rule("rule", "Ударение", "Ударный слог произносится сильнее и протяжнее других. В слове он один. Чтобы его найти, позови слово или задай вопрос голосом: это самолёт?"),
      s.choice("guided", "guided", "Слоги", "Самолёт: са-мо-лёт. Какой слог ударный?", ["лёт", "са", "мо"], "лёт", "Позови: са-мо-лёёёт."),
      s.choice("practice-1", "practice", "Слоги", "Какой слог ударный в слове «облако»?", ["об", "ла", "ко"], "об", "Позови: ооб-ла-ко."),
      s.choice("practice-2", "practice", "Слоги", "Какой слог ударный в слове «штурвал»?", ["штур", "вал"], "вал", "Позови: штур-вааал."),
      s.choice("transfer", "transfer", "Логика", "Вера говорит: «Если в слове замок поставить ударение на другой слог, получится другое слово». Права ли она?", ["Права", "Ошиблась"], "Права", "Вспомни замок на двери и замок у принцессы."),
      s.say("reflect", "reflect", "Теперь ты находишь ударный слог: зовёшь слово голосом и слушаешь, какой слог тянется."),
    ],
    "Русский язык",
  );
}

