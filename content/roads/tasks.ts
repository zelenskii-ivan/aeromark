export const taskById = (id: string) =>
  ROAD_TASKS.find((task) => task.id === id);
export function correctRoadAnswer(task: RoadTask, picked: number[]): boolean {
  if (new Set(picked).size !== picked.length) return false;
  const actual = task.kind === "order" ? picked : [...picked].sort();
  const expected =
    task.kind === "order" ? task.answer : [...task.answer].sort();
  return (
    actual.length === expected.length &&
    actual.every((value, i) => value === expected[i])
  );
}
